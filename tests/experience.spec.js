import { test, expect } from '@playwright/test';

async function answer(page) {
  await page.getByRole('button', { name: 'Confirm 50 / 100' }).click();
  await page.getByRole('button', { name: 'Somewhat confident', exact: true }).click();
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await page.getByLabel('In your own words').fill('I want to feel secure when I retire.');
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await page.getByRole('button', { name: 'Plan confidently for the long term', exact: true }).click();
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await page.getByLabel('In your own words').fill('I am unsure about the timing of this goal.');
  await page.getByRole('button', { name: 'Review my answers' }).click();
  await expect(page.getByText('“I want to feel secure when I retire.”', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Meet your plan' }).click();
}

test('desktop: literal quote, tension, real finding, sources, mission and check-in', async ({ page }) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto('/');
  await expect(page.getByRole('button', { name: 'Open Samantha', exact: true })).toBeVisible();
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({ path: 'test-results/cover-desktop.png', fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: 'Open Samantha', exact: true }).click();
  await page.screenshot({ path: 'test-results/conversation-desktop.png', fullPage: true, animations: 'disabled' });
  await answer(page);
  await expect(page.getByRole('heading', { name: 'You told us.' })).toBeVisible();
  await expect(page.getByText('“I want to feel secure when I retire.”', { exact: true })).toBeVisible();
  await expect(page.locator('.actual-number')).toHaveCount(0);
  await page.getByRole('button', { name: 'Open my plan' }).click();
  await expect(page.getByRole('button', { name: 'Skip transition' })).toBeVisible();
  await page.getByRole('button', { name: 'Skip transition' }).click();
  await expect(page.locator('.actual-number')).toHaveText('82/100');
  await expect(page.getByText('A strong score. A longer story.')).toBeVisible();
  await page.screenshot({ path: 'test-results/score-desktop.png', fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: 'Look beyond the score' }).click();
  await expect(page.getByRole('heading', { name: 'Savings and investments run out at age 73' })).toBeVisible();
  await expect(page.locator('.finding-page')).toHaveCount(1);
  await page.getByLabel('Your question').fill('Hi how can I make pancakes?');
  await page.getByRole('button', { name: 'Explore this finding' }).click();
  await expect(page.getByRole('status')).toContainText('outside this finding');
  await page.screenshot({ path: 'test-results/finding-desktop.png', fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: 'Numbers & context' }).click();
  await expect(page.locator('.finding-figure')).toHaveText('$1,448,672.53');
  await page.getByRole('button', { name: 'Open the source', exact: true }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await expect(page.getByRole('dialog')).toContainText('In your plan');
  await expect(page.getByRole('dialog')).not.toContainText('/key_metrics/');
  await expect(page.getByRole('dialog')).not.toContainText('replaces');
  await page.keyboard.press('Escape');
  await expect(page.getByRole('button', { name: 'Open the source', exact: true })).toBeFocused();
  await page.getByRole('button', { name: 'Discuss with my advisor' }).click();
  await expect(page.getByRole('status')).toContainText('Saved for your advisor');
  await page.getByRole('button', { name: 'Next finding', exact: true }).click();
  await page.getByRole('button', { name: 'Next finding', exact: true }).click();
  await page.getByRole('button', { name: 'Bring it together' }).click();
  await page.getByRole('button', { name: 'Choose a next step' }).click();
  await page.getByRole('button', { name: 'I’ll take this step' }).click();
  await page.getByRole('button', { name: 'Try a follow-up' }).click();
  await page.getByRole('button', { name: /I made a start/ }).click();
  await page.getByLabel('Anything you’d like to add?').fill('Reviewed the source.');
  await page.getByRole('button', { name: 'Save my check-in' }).click();
  await expect(page.getByText('Status: in progress', { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Plans meet life. How did it go?' })).toBeVisible();
  await expect(page.getByText('Status: in progress', { exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});

test('mobile: import a different schema, missing score, reduced motion and no overflow', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto('/');
  await expect(page.getByRole('button', { name: 'Open Samantha', exact: true })).toBeVisible();
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({ path: 'test-results/cover-mobile.png', fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: 'Import a client plan' }).click();
  await page.getByLabel('Choose a client JSON file').setInputFiles({ name: 'different-client.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ client: 'Jordan Test', content: 'Discuss the timing of your goals with your advisor.' })) });
  await expect(page.getByText('Choose the matching fields.', { exact: false })).toBeVisible();
  await page.getByLabel('Client name', { exact: true }).selectOption('/client');
  await page.getByLabel('Plan summary', { exact: true }).selectOption('/content');
  await page.getByRole('button', { name: 'Add this client' }).click();
  await page.getByRole('button', { name: 'Open Jordan Test', exact: true }).last().click();
  await answer(page);
  await page.getByRole('button', { name: 'Open my plan' }).click();
  await expect(page.getByText('No financial health score in this export')).toBeVisible();
  await page.getByRole('button', { name: 'Look beyond the score' }).click();
  await expect(page.getByRole('heading', { name: 'The bigger picture', exact: true })).toBeVisible();
  await page.screenshot({ path: 'test-results/finding-mobile.png', fullPage: true, animations: 'disabled' });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Open the source', exact: true }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.screenshot({ path: 'test-results/source-mobile.png', fullPage: true, animations: 'disabled' });
  await page.keyboard.press('Escape');
  await page.reload();
  await expect(page.getByRole('heading', { name: 'You told us.' })).toBeVisible();
});
